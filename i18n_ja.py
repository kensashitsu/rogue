import unicodedata


def _w(s: str) -> int:
    return sum(2 if unicodedata.east_asian_width(c) in 'WF' else 1 for c in s)


def _row(left: str, right: str = "", col: int = 23) -> str:
    """ヘルプの2列表示。右列を見た目の col 列目から始める。"""
    if not right:
        return left
    return left + " " * max(1, col - _w(left)) + right


